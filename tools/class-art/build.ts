// Builds apps/ui/src/class-art.ts: where each ascendancy's portrait sits on the passive tree's ascendancy
// sprite sheet, for the class tile on the Search view. The source is PoB's own TreeData/<version>/sprites.lua
// (the "ascendancy" sheet's "Classes<Name>" tiles); the sheet itself loads from web.poecdn.com, as PoB's
// GUI does. Rebuild when a league changes the tree.
//
//   node tools/class-art/build.ts <PoB src/TreeData/<version>/sprites.lua>

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

interface Tile {
    readonly x: number;
    readonly y: number;
    readonly w: number;
    readonly h: number;
}

function numberAt(block: string, key: string): number {
    const m: RegExpMatchArray | null = block.match(new RegExp(`\\["${key}"\\]\\s*=\\s*(\\d+)`));
    if (m === null || m[1] === undefined) {
        throw new Error(`sprites.lua: no ${key} in ${block.slice(0, 80)}`);
    }
    return Number(m[1]);
}

function main(): void {
    const source: string | undefined = process.argv[2];
    if (source === undefined) {
        throw new Error('usage: node tools/class-art/build.ts <PoB src/TreeData/<version>/sprites.lua>');
    }
    const text: string = readFileSync(source, 'utf8');
    const start: number = text.indexOf('["ascendancy"]=');
    if (start < 0) {
        throw new Error('sprites.lua: no "ascendancy" sheet');
    }
    // The sheet's block ends where the next top-level sheet starts.
    const next: number = text.slice(start + 1).search(/\n {8}\["[A-Za-z]+"\]=/);
    const block: string = next < 0 ? text.slice(start) : text.slice(start, start + 1 + next);
    const file: RegExpMatchArray | null = block.match(/\["filename"\]\s*=\s*"([^"]+)"/);
    if (file === null || file[1] === undefined || !file[1].startsWith('https://web.poecdn.com/')) {
        throw new Error('sprites.lua: the ascendancy sheet has no web.poecdn.com filename');
    }
    const header: string = block.slice(0, block.indexOf('["coords"]'));
    const sheet = { url: file[1], w: numberAt(header, 'w'), h: numberAt(header, 'h') };
    const tiles: Record<string, Tile> = {};
    for (const m of block.matchAll(/\["Classes([A-Za-z]+)"\]\s*=\s*\{([^}]*)\}/g)) {
        const name: string | undefined = m[1];
        const body: string | undefined = m[2];
        if (name === undefined || body === undefined || name === 'Alternate') {
            continue;
        }
        tiles[name] = { x: numberAt(body, 'x'), y: numberAt(body, 'y'), w: numberAt(body, 'w'), h: numberAt(body, 'h') };
    }
    const names: string[] = Object.keys(tiles).sort();
    if (names.length < 19) {
        throw new Error(`sprites.lua: only ${names.length} ascendancy tiles found`);
    }
    const lines: string[] = [
        "// Generated by tools/class-art/build.ts from PoB's TreeData sprites.lua: do not edit by hand.",
        "// Each ascendancy's portrait on the passive tree's ascendancy sprite sheet (Search view, class tile).",
        '',
        'export interface ClassArtTile {',
        '    readonly x: number;',
        '    readonly y: number;',
        '    readonly w: number;',
        '    readonly h: number;',
        '}',
        '',
        `export const CLASS_ART_SHEET = { url: '${sheet.url}', w: ${sheet.w}, h: ${sheet.h} } as const;`,
        '',
        'export const CLASS_ART: Readonly<Record<string, ClassArtTile>> = {',
        ...names.map((n: string) => {
            const t: Tile | undefined = tiles[n];
            return t === undefined ? '' : `    ${n}: { x: ${t.x}, y: ${t.y}, w: ${t.w}, h: ${t.h} },`;
        }),
        '};',
        '',
    ];
    const out: string = resolve(dirname(fileURLToPath(import.meta.url)), '../../apps/ui/src/class-art.ts');
    writeFileSync(out, lines.join('\n'));
    console.log(`${names.length} ascendancies written to ${out}`);
}

main();
